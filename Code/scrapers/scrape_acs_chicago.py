"""Build the Chicago per-ZIP static table: the eight demographic columns.

    . ~/.bash_profile                # CENSUS_API_KEY lives there
    python Code/scrapers/scrape_acs_chicago.py

Why this exists at all. The frozen backtest arms `gnn_st`, `gnn_st_nograph`,
`xgboost` and `xgboost_parity` all read static demographics (gnn_st as node
features and as demographic-similarity edges), and
`cli.check_experiment_supported` refuses them for a city that lacks the
'demographics' feature. The ablations found the eight columns inert, but the
backtest freezes its arms before scoring, so the honest options were "fetch
them" or "leave the headline arm out of a city's evidence". Fetching is one
API call.

Thin by design: the ACS variable list, the numerator/denominator pairs and the
fetcher are imported from scrape_acs_columbus.py, so the two US cities'
columns are the same construct by construction. Two differences:

  * NO AGGREGATION. Chicago's nodes are ZIPs, so each node is one ZCTA. (ZIP
    and ZCTA are not identical: 58 of the 59 have a ZCTA of the same number;
    60666, O'Hare, has no residents and no ZCTA.)
  * LAND AREA FROM THE CITY'S OWN POLYGONS. `shape_area` in unjd-c2ca is in
    square feet (Illinois State Plane), so pop_density needs no Gazetteer pull.

Population is written too, but it is NOT a rate denominator here -- the
Chicago series is a 1-10 activity level with no count behind it.

Output: Data/Chicago/chicago_zip_static.csv. Raw ratios; min-max scaling
happens in influenza/loaders/chicago.py, as for every other city.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from influenza import paths  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "scrape_acs_columbus", Path(__file__).resolve().parent / "scrape_acs_columbus.py")
_columbus = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_columbus)

SQFT_PER_SQMI = 5280.0 ** 2


def land_sqmi() -> pd.Series:
    with open(paths.require(paths.CHICAGO_BOUNDARIES_FILE, "Chicago ZIP polygons")) as handle:
        features = json.load(handle)["features"]
    return pd.Series({str(f["properties"]["zip"]).zfill(5):
                      float(f["properties"]["shape_area"]) / SQFT_PER_SQMI
                      for f in features}, name="land_sqmi")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--acs-year", type=int, default=_columbus.DEFAULT_ACS_YEAR)
    parser.add_argument("--output", type=Path, default=paths.CHICAGO_STATIC_FILE)
    args = parser.parse_args()

    key = os.environ.get("CENSUS_API_KEY", "").strip()
    if not key:
        raise SystemExit("CENSUS_API_KEY is not set (run `. ~/.bash_profile` first). "
                         "Free keys: https://api.census.gov/data/key_signup.html")

    coverage = pd.read_csv(paths.require(paths.CHICAGO_COVERAGE_FILE, "Chicago coverage"),
                           dtype={"zip": str})
    zips = sorted(coverage["zip"])
    print(f"ACS {args.acs_year} 5-year, {len(_columbus.ACS_VARIABLES)} variables...")
    acs = _columbus.fetch_acs(args.acs_year, key)
    # 60666 is O'Hare: a USPS ZIP with no residents, so the Census defines no
    # ZCTA for it. Its row stays NaN here and the loader fills it with the city
    # median, the same fill Boston's data.py uses for a missing district value.
    missing = sorted(set(zips) - set(acs.index))
    if missing:
        print(f"  no ZCTA (left NaN, median-filled by the loader): {missing}")
    counts = acs.reindex(zips)

    static = pd.DataFrame(index=pd.Index(zips, name="zip"))
    static["population"] = counts[_columbus.POPULATION]
    static["land_sqmi"] = land_sqmi().reindex(zips)
    static["pop_density"] = static["population"] / static["land_sqmi"]
    for name, (numerator, denominator, invert) in _columbus.FEATURES.items():
        ratio = counts[numerator].sum(axis=1) / counts[denominator].sum(axis=1)
        static[name] = (1.0 - ratio) if invert else ratio

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with open(args.output, "w") as handle:
        handle.write(
            "# Chicago per-ZIP static features. Generated by Code/scrapers/"
            "scrape_acs_chicago.py\n"
            f"# Sources: Census ACS {args.acs_year} 5-year (detailed tables, per ZCTA);\n"
            "# land area from shape_area in the City's ZIP polygons (unjd-c2ca).\n"
            "# DERIVED BY THIS PROJECT. Ratios are raw; min-max scaling happens in\n"
            "# influenza/loaders/chicago.py. Population is NOT a rate denominator:\n"
            "# the Chicago target is a 1-10 activity level.\n")
        static.to_csv(handle)

    gaps = static.columns[static.isna().any()].tolist()
    print(f"{len(static)} ZIPs -> {paths.display(args.output, paths.ROOT)}")
    print(f"Total population: {static['population'].sum():,.0f}")
    if gaps:
        print(f"Columns with gaps (filled by the loader): "
              f"{ {c: static.index[static[c].isna()].tolist() for c in gaps} }")
    print(static[["population", "pop_density", "poverty_rate", "transit_share",
                  "nonwhite_share"]].describe().round(3).to_string())


if __name__ == "__main__":
    main()
